#!/usr/bin/env python3
"""Generates generated/html_entities.rs from the entities.json of the HTML standard:
https://html.spec.whatwg.org/entities.json

usage: generate_entities.py entities.json generated/html_entities.rs
"""
import json
import sys


def main():
    with open(sys.argv[1], encoding="utf-8") as source:
        entities = json.load(source)
    # Names are searched by their bytes, without the leading '&'.
    rows = sorted((name[1:], entity["codepoints"]) for name, entity in entities.items())
    rows.sort(key=lambda row: row[0].encode())
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/generate_entities.py. Do not edit.\n\n")
        out.write("/// Character reference names, sorted by bytes, with and without `;` as in the standard.\n")
        out.write("#[rustfmt::skip]\n")
        out.write("pub(super) static ENTITIES: &[(&str, &str)] = &[\n")
        for name, codepoints in rows:
            value = "".join(f"\\u{{{point:x}}}" for point in codepoints)
            out.write(f'    ("{name}", "{value}"),\n')
        out.write("];\n")


if __name__ == "__main__":
    main()
